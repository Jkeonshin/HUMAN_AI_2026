# 1. 이미지 파일을 읽는다.
# 2. AI 서버에 접속한다.
# 3. 이미지 크기와 실제 이미지를 서버로 전송한다.
# 4. 서버가 반환한 AI 분류 결과를 받는다.
# 5. 결과를 출력하고 연결을 종료한다.
