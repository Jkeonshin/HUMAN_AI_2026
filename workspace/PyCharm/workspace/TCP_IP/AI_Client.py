# ----------------------------------------------------------
# 1. 필요한 라이브러리 불러오기
# ----------------------------------------------------------

import socket  # TCP/IP 클라이언트 통신
import struct  # 정수와 4바이트 데이터 상호 변환
import json    # JSON 문자열을 파이썬 딕셔너리로 변환


# ----------------------------------------------------------
# 2. 접속할 AI 서버의 IP와 포트 설정
# 서버 코드의 HOST, PORT와 동일해야 한다.
# ----------------------------------------------------------

HOST = "192.168.133.107"  # AI 서버 컴퓨터의 IP
PORT = 9997               # AI 서버가 사용하는 포트


# ----------------------------------------------------------
# 3. 서버로 전송할 테스트 이미지 경로 설정
# cat.jpg 대신 horse.jpg를 사용할 수도 있다.
# ----------------------------------------------------------

IMAGE_PATH = "./cat.jpg"

# 말 이미지로 테스트할 경우
# IMAGE_PATH = "./horse.jpg"


# ----------------------------------------------------------
# 4. 지정한 크기만큼 데이터를 모두 수신하는 함수
# TCP 데이터가 여러 조각으로 들어올 수 있으므로 반복해서 받는다.
# ----------------------------------------------------------

def recv_all(sock, size):

    # 수신 데이터를 저장할 빈 바이트 변수
    data = b""

    # 지정된 크기만큼 받을 때까지 반복
    while len(data) < size:

        # 아직 받지 못한 크기만큼 데이터 수신
        packet = sock.recv(
            size - len(data)
        )

        # 데이터가 들어오지 않으면 연결 종료로 판단
        if not packet:
            return None

        # 새로 받은 데이터를 기존 데이터 뒤에 추가
        data += packet

    # 지정된 크기만큼 받은 데이터를 반환
    return data


# ----------------------------------------------------------
# 5. 이미지 파일 읽기
# rb: 이미지 파일을 바이너리 바이트 형태로 읽는다.
# ----------------------------------------------------------

print("이미지 읽기 시작")

with open(IMAGE_PATH, "rb") as f:

    # 이미지 파일 전체를 바이트 데이터로 저장
    image_data = f.read()

print("이미지 읽기 완료")

print(
    "이미지 크기:",
    len(image_data),
    "byte"
)


# ----------------------------------------------------------
# 6. TCP 클라이언트 소켓 생성
# AF_INET     : IPv4 주소 사용
# SOCK_STREAM : TCP 통신 사용
# ----------------------------------------------------------

client_socket = socket.socket(
    socket.AF_INET,
    socket.SOCK_STREAM
)

print("클라이언트 소켓 생성 완료")


# ----------------------------------------------------------
# 7. AI 서버에 접속
# 서버가 먼저 실행되어 접속을 기다리고 있어야 한다.
# ----------------------------------------------------------

print("서버 접속 시도")

client_socket.connect(
    (HOST, PORT)
)

print("서버 접속 성공")


# ----------------------------------------------------------
# 8. 이미지 데이터의 전체 크기 계산
# ----------------------------------------------------------

image_size = len(image_data)

print(
    "전송 이미지 크기:",
    image_size,
    "byte"
)


# ----------------------------------------------------------
# 9. 이미지 크기를 4바이트로 변환하여 먼저 전송
#
# >I 의미
# > : 빅 엔디언 방식
# I : 부호 없는 정수 4바이트
#
# 서버는 이 정보를 보고 받아야 할 이미지 크기를 확인한다.
# ----------------------------------------------------------

image_size_header = struct.pack(
    ">I",
    image_size
)

client_socket.sendall(
    image_size_header
)

print("이미지 크기 전송 완료")


# ----------------------------------------------------------
# 10. 실제 이미지 바이트 데이터 전송
# ----------------------------------------------------------

client_socket.sendall(
    image_data
)

print("이미지 데이터 전송 완료")


# ----------------------------------------------------------
# 11. 서버가 보낸 결과 크기 4바이트 수신
# 서버도 실제 JSON보다 결과 크기를 먼저 전송한다.
# ----------------------------------------------------------

header = recv_all(
    client_socket,
    4
)

# 서버 연결이 끊겨 헤더를 받지 못한 경우
if header is None:

    print("결과 크기를 수신하지 못했습니다.")

    client_socket.close()

    raise ConnectionError(
        "AI 서버와의 연결이 종료되었습니다."
    )


# ----------------------------------------------------------
# 12. 수신한 4바이트를 결과 크기 정수로 변환
# ----------------------------------------------------------

result_size = struct.unpack(
    ">I",
    header
)[0]

print(
    "결과 크기:",
    result_size,
    "byte"
)


# ----------------------------------------------------------
# 13. 확인한 결과 크기만큼 실제 JSON 데이터 수신
# ----------------------------------------------------------

result_bytes = recv_all(
    client_socket,
    result_size
)

# 결과 데이터를 받지 못한 경우
if result_bytes is None:

    print("결과 데이터를 수신하지 못했습니다.")

    client_socket.close()

    raise ConnectionError(
        "AI 서버와의 연결이 종료되었습니다."
    )

print("결과 데이터 수신 완료")


# ----------------------------------------------------------
# 14. JSON 바이트를 파이썬 딕셔너리로 변환
#
# 바이트
# → 문자열
# → 파이썬 딕셔너리
# ----------------------------------------------------------

result_json = result_bytes.decode()

result = json.loads(
    result_json
)

print("JSON 변환 완료")


# ----------------------------------------------------------
# 15. AI 이미지 분류 결과 출력
# ----------------------------------------------------------

print()
print("====================")
print("AI 분류 결과")
print("====================")

# 예측 클래스 번호 출력
print(
    "Class ID:",
    result["class_id"]
)

# 예측 클래스 이름 출력
print(
    "Class Name:",
    result["class_name"]
)

# 예측 신뢰도를 소수점 넷째 자리까지 출력
print(
    "Confidence:",
    round(
        result["confidence"],
        4
    )
)

print("====================")


# ----------------------------------------------------------
# 16. AI 서버와의 연결 종료
# ----------------------------------------------------------

client_socket.close()

print("서버 연결 종료")





