# ==========================================================
# AI_Server.py
# 클라이언트가 전송한 이미지를 CIFAR-10 모델로 분류하는 서버
# ==========================================================


# ----------------------------------------------------------
# 1. 필요한 라이브러리 불러오기
# ----------------------------------------------------------

import socket          # TCP/IP 서버 통신
import struct          # 정수와 4바이트 데이터 상호 변환
import json            # 예측 결과를 JSON으로 변환
import numpy as np     # 이미지 배열 처리
import tensorflow as tf  # 학습된 AI 모델 불러오기 및 예측

from PIL import Image  # 이미지 열기 및 크기 변경
from io import BytesIO # 이미지 바이트를 파일처럼 처리


# ----------------------------------------------------------
# 2. CIFAR-10 클래스 이름 설정
# 모델의 예측 번호를 실제 이름으로 바꿀 때 사용
# ----------------------------------------------------------

CLASS_NAMES = [
    "airplane",     # 0
    "automobile",   # 1
    "bird",         # 2
    "cat",          # 3
    "deer",         # 4
    "dog",          # 5
    "frog",         # 6
    "horse",        # 7
    "ship",         # 8
    "truck"         # 9
]


# ----------------------------------------------------------
# 3. AI_model.py에서 학습하고 저장한 모델 불러오기
# ----------------------------------------------------------

print("AI 모델 로딩 시작")

model = tf.keras.models.load_model(
    "./model/cifar10_model.h5"
)

print("AI 모델 로딩 완료")


# ----------------------------------------------------------
# 4. 지정한 크기만큼 데이터를 모두 수신하는 함수
# TCP는 데이터가 나누어 들어올 수 있으므로 반복 수신
# ----------------------------------------------------------

def recv_all(sock, size):

    data = b""  # 수신 데이터를 저장할 빈 바이트 변수

    # 지정된 크기만큼 받을 때까지 반복
    while len(data) < size:

        packet = sock.recv(
            size - len(data)
        )

        # 데이터가 들어오지 않으면 연결 종료로 판단
        if not packet:
            return None

        # 새로 받은 데이터를 기존 데이터 뒤에 추가
        data += packet

    # 지정한 크기만큼 받은 데이터를 반환
    return data


# ----------------------------------------------------------
# 5. 수신한 이미지를 CIFAR-10 모델로 예측하는 함수
# ----------------------------------------------------------

def predict_image(image_bytes):

    # 5-1. 이미지 바이트를 PIL 이미지로 변환
    image = Image.open(
        BytesIO(image_bytes)
    )

    # 5-2. 이미지를 RGB 컬러 형식으로 변환
    image = image.convert("RGB")

    # 5-3. CIFAR-10 모델 입력 크기인 32×32로 변경
    image = image.resize(
        (32, 32)
    )

    # 5-4. PIL 이미지를 NumPy 배열로 변환
    image = np.array(image)

    # 5-5. 픽셀값을 0~255에서 0~1 범위로 정규화
    image = image / 255.0

    # 5-6. 이미지 한 장을 모델에 넣을 수 있도록 차원 추가
    # (32, 32, 3) → (1, 32, 32, 3)
    image = np.expand_dims(
        image,
        axis=0
    )

    print("입력 shape:", image.shape)

    # 5-7. 학습된 모델로 이미지 예측
    pred = model.predict(
        image,
        verbose=0
    )

    print("예측 확률")
    print(pred)

    # 5-8. 확률이 가장 높은 클래스 번호 확인
    class_idx = np.argmax(pred)

    # 5-9. 가장 높은 예측 확률 확인
    confidence = np.max(pred)

    print("예측 클래스:", class_idx)
    print("신뢰도:", confidence)

    # 5-10. 클라이언트에 전송할 결과 생성
    result = {
        "class_id": int(class_idx),
        "class_name": CLASS_NAMES[class_idx],
        "confidence": float(confidence)
    }

    return result


# ----------------------------------------------------------
# 6. 서버 IP와 포트 설정
# ----------------------------------------------------------

HOST = "192.168.133.107"  # 서버 컴퓨터의 IP 주소
PORT = 9997               # 클라이언트가 접속할 포트 번호


# ----------------------------------------------------------
# 7. TCP 서버 소켓 생성
# AF_INET     : IPv4 주소 사용
# SOCK_STREAM : TCP 통신 사용
# ----------------------------------------------------------

server_socket = socket.socket(
    socket.AF_INET,
    socket.SOCK_STREAM
)

print("서버 소켓 생성 완료")


# ----------------------------------------------------------
# 8. 서버 소켓에 IP와 포트 바인딩
# ----------------------------------------------------------

server_socket.bind(
    (HOST, PORT)
)

print("호스트와 포트 바인딩 완료")


# ----------------------------------------------------------
# 9. 클라이언트 접속 대기 시작
# 5개의 접속 요청을 대기열에 저장 가능
# ----------------------------------------------------------

server_socket.listen(5)

print(f"AI 서버 시작: {HOST}:{PORT}")


# ----------------------------------------------------------
# 10. 서버 반복 실행
# 한 클라이언트 처리가 끝나면 다음 접속을 다시 기다림
# ----------------------------------------------------------

while True:

    print("\n클라이언트 접속 대기 중")


    # ------------------------------------------------------
    # 11. 클라이언트가 접속할 때까지 기다린 후 접속 수락
    # ------------------------------------------------------

    client_socket, addr = server_socket.accept()

    print("클라이언트 접속:", addr)


    try:

        # --------------------------------------------------
        # 12. 이미지 크기가 저장된 4바이트 헤더 수신
        # --------------------------------------------------

        header = recv_all(
            client_socket,
            4
        )

        # 헤더를 받지 못한 경우
        if header is None:
            print("클라이언트 연결 종료 또는 데이터 수신 실패")
            continue


        # --------------------------------------------------
        # 13. 4바이트 데이터를 이미지 크기 정수로 변환
        # --------------------------------------------------

        image_size = struct.unpack(
            ">I",
            header
        )[0]

        print("이미지 크기:", image_size)


        # --------------------------------------------------
        # 14. 확인한 크기만큼 실제 이미지 데이터 수신
        # --------------------------------------------------

        image_bytes = recv_all(
            client_socket,
            image_size
        )

        if image_bytes is None:
            print("이미지 데이터 수신 실패")
            continue

        print("이미지 수신 완료")


        # --------------------------------------------------
        # 15. CIFAR-10 모델로 이미지 예측
        # --------------------------------------------------

        result = predict_image(
            image_bytes
        )

        print("예측 결과:", result)


        # --------------------------------------------------
        # 16. 예측 결과를 JSON 바이트로 변환
        # Python 딕셔너리 → JSON 문자열 → 바이트
        # --------------------------------------------------

        result_json = json.dumps(
            result,
            ensure_ascii=False
        ).encode()


        # --------------------------------------------------
        # 17. JSON 결과의 크기를 4바이트로 먼저 전송
        # --------------------------------------------------

        result_size = len(result_json)

        client_socket.sendall(
            struct.pack(
                ">I",
                result_size
            )
        )


        # --------------------------------------------------
        # 18. 실제 JSON 예측 결과 전송
        # --------------------------------------------------

        client_socket.sendall(
            result_json
        )

        print("결과 전송 완료")


    # ------------------------------------------------------
    # 19. 이미지 처리 중 오류가 발생한 경우
    # ------------------------------------------------------

    except Exception as e:

        print("오류 발생:", e)


    # ------------------------------------------------------
    # 20. 성공 또는 오류 여부와 관계없이 클라이언트 종료
    # ------------------------------------------------------

    finally:

        client_socket.close()

        print("클라이언트 연결 종료")


    # ------------------------------------------------------
    # 21. while True의 처음으로 돌아가
    # 다음 클라이언트의 접속을 다시 기다림
    # ------------------------------------------------------