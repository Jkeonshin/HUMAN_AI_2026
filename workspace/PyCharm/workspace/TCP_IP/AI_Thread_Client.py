# ==========================================================
# 10. JSON 데이터 변환 과정
# ==========================================================
#
# 요청을 보낼 때:
#
# 사용자 입력
#     ↓
# 파이썬 딕셔너리
#     ↓ json.dumps()
# JSON 문자열
#     ↓ encode()
