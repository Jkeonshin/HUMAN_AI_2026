# ==========================================================
# AI_Thread_Client.py
#
# 멀티 클라이언트 텍스트 분석 요청 프로그램
#
# - 사용자가 분석 모드와 문장을 입력한다.
# - 입력 내용을 JSON 형태로 서버에 전송한다.
# - 서버가 반환한 분석 결과를 수신한다.
# - 결과를 화면에 출력한다.
# - exit를 입력하면 서버 연결을 종료한다.
# ==========================================================


# ----------------------------------------------------------
# 1. 필요한 라이브러리 불러오기
# ----------------------------------------------------------

import socket  # TCP/IP 클라이언트 통신
import json    # 파이썬 딕셔너리와 JSON 데이터 상호 변환


# ----------------------------------------------------------
# 2. 접속할 서버의 IP와 포트 설정
#
# 클라이언트 자신의 IP가 아니라
# 접속할 서버 컴퓨터의 IP를 입력해야 한다.
# ----------------------------------------------------------

HOST = "192.168.133.118"  # 강사 서버 IP
PORT = 9997               # 강사 서버 포트


# ----------------------------------------------------------
# 3. TCP 클라이언트 소켓 생성
#
# AF_INET     : IPv4 주소 사용
# SOCK_STREAM : TCP 통신 사용
# ----------------------------------------------------------

client_socket = socket.socket(
    socket.AF_INET,
    socket.SOCK_STREAM
)


# ----------------------------------------------------------
# 4. 강사 서버에 접속
# 서버가 먼저 실행되어 있어야 한다.
# ----------------------------------------------------------

client_socket.connect(
    (HOST, PORT)
)

print("서버에 연결되었습니다.")
print("종료하려면 분석 모드에 'exit'를 입력하세요.\n")


# ----------------------------------------------------------
# 5. 사용자 입력과 서버 송수신 반복
#
# exit를 입력하기 전까지 계속 반복한다.
# ----------------------------------------------------------

while True:


    # ------------------------------------------------------
    # 5-1. 사용자에게 분석 모드 입력받기
    #
    # length    : 글자 수 분석
    # sentiment : 감정 분석
    # keyword   : 키워드 탐지
    # ------------------------------------------------------

    mode = input(
        "분석 모드 (length / sentiment / keyword): "
    ).strip()


    # ------------------------------------------------------
    # 5-2. exit를 입력한 경우 반복문 종료
    #
    # 반복문을 빠져나가면 아래의 client_socket.close()가
    # 실행되면서 서버와의 연결이 종료된다.
    # ------------------------------------------------------

    if mode.lower() == "exit":

        print("클라이언트를 종료합니다.")

        break


    # ------------------------------------------------------
    # 5-3. 서버에서 분석할 문장 입력받기
    # ------------------------------------------------------

    text = input(
        "분석할 문장 입력: "
    ).strip()


    # ------------------------------------------------------
    # 5-4. 분석 모드와 문장을 딕셔너리로 구성
    #
    # 예시:
    #
    # {
    #     "mode": "sentiment",
    #     "text": "오늘 기분이 좋아"
    # }
    # ------------------------------------------------------

    request = {
        "mode": mode,
        "text": text
    }


    # ------------------------------------------------------
    # 5-5. 요청 딕셔너리를 JSON 문자열로 변환
    #
    # ensure_ascii=False
    # → 한글을 그대로 유지
    # ------------------------------------------------------

    request_json = json.dumps(
        request,
        ensure_ascii=False
    )


    # ------------------------------------------------------
    # 5-6. JSON 문자열을 바이트로 변환하여 서버에 전송
    #
    # 파이썬 딕셔너리
    # → JSON 문자열
    # → 바이트
    # → 서버 전송
    # ------------------------------------------------------

    client_socket.sendall(
        request_json.encode()
    )


    # ------------------------------------------------------
    # 5-7. 서버가 전송한 분석 결과 수신
    #
    # 최대 2,048바이트를 수신한 뒤
    # 바이트 데이터를 문자열로 변환한다.
    # ------------------------------------------------------

    data = client_socket.recv(
        2048
    ).decode()


    # ------------------------------------------------------
    # 5-8. 서버에서 데이터가 오지 않은 경우
    # 서버 연결이 종료된 것으로 판단
    # ------------------------------------------------------

    if not data:

        print("서버와의 연결이 종료되었습니다.")

        break


    # ------------------------------------------------------
    # 5-9. 서버 응답 JSON을 파이썬 딕셔너리로 변환
    # ------------------------------------------------------

    try:

        response = json.loads(data)


        # --------------------------------------------------
        # 5-10. 서버의 분석 결과를 보기 좋게 출력
        #
        # indent=2
        # → JSON 데이터에 들여쓰기 적용
        # --------------------------------------------------

        print(
            f"\n서버 응답:\n"
            f"{json.dumps(response, ensure_ascii=False, indent=2)}\n"
        )


    # ------------------------------------------------------
    # 5-11. 서버 응답이 올바른 JSON이 아닌 경우
    # ------------------------------------------------------

    except json.decoder.JSONDecodeError:

        print(
            f"\n서버 응답 오류: {data}\n"
        )


    # ------------------------------------------------------
    # 5-12. while True의 처음으로 돌아가
    # 다음 분석 모드를 다시 입력받는다.
    # ------------------------------------------------------


# ----------------------------------------------------------
# 6. 서버와의 연결 종료
#
# exit 입력, 서버 종료 등의 이유로 반복문이 끝나면 실행된다.
# ----------------------------------------------------------

client_socket.close()

print("클라이언트 종료 완료")


# ==========================================================
# 7. AI_Thread_Client.py 전체 실행 순서
# ==========================================================
#
# 1. 필요한 라이브러리 불러오기
# 2. 접속할 서버 IP와 포트 설정
# 3. TCP 클라이언트 소켓 생성
# 4. 강사 서버에 접속
# 5. 분석 모드 입력
# 6. exit인지 확인
# 7. 분석할 문장 입력
# 8. 모드와 문장을 딕셔너리로 구성
# 9. 딕셔너리를 JSON 문자열로 변환
# 10. JSON을 바이트로 변환하여 서버에 전송
# 11. 서버의 분석 결과 수신
# 12. JSON 응답을 파이썬 딕셔너리로 변환
# 13. 분석 결과 출력
# 14. 다음 분석 모드 입력으로 돌아가기
# 15. exit를 입력하면 반복 종료
# 16. 클라이언트 소켓 종료
#
#
# ==========================================================
