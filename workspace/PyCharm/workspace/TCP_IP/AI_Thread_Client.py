#
# 서버에 전송되는 JSON:
#
# {
#     "mode": "sentiment",
#     "text": "오늘 수업이 재미있고 기분이 좋아"
# }
#
#
# ③ 키워드 분석
#
# 사용자 입력:
#
# 분석 모드: keyword
