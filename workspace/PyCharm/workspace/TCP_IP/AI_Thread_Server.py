# ==========================================================
# AI_Thread_Server.py
#
# 멀티 클라이언트 텍스트 분석 서버
#
# - 여러 클라이언트가 동시에 접속할 수 있다.
# - 클라이언트가 JSON 형태로 분석 요청을 보낸다.
# - 서버는 요청에 따라 텍스트를 분석한다.
# - 분석 결과를 JSON 형태로 클라이언트에 반환한다.
# - 접속한 클라이언트마다 별도의 스레드를 생성한다.
# ==========================================================


# ----------------------------------------------------------
# 1. 필요한 라이브러리 불러오기
# ----------------------------------------------------------

import socket     # TCP/IP 서버 통신
import threading  # 여러 클라이언트를 동시에 처리
import json       # JSON 데이터 변환


# ----------------------------------------------------------
# 2. 서버 IP와 포트 설정
# ----------------------------------------------------------

HOST = "192.168.133.118"  # 서버 컴퓨터의 IP 주소
PORT = 9997               # 클라이언트가 접속할 포트 번호

# 동시에 연결할 수 있는 최대 클라이언트 수
MAX_CLIENTS = 20


# ----------------------------------------------------------
# 3. 클라이언트가 보낸 문장을 분석하는 함수
#
# request 예시:
#
# {
#     "mode": "sentiment",
#     "text": "오늘 기분이 좋아"
# }
# ----------------------------------------------------------

def analyze_text(request: dict):

    # JSON 요청에서 분석 모드 가져오기
    mode = request.get("mode")

    # JSON 요청에서 분석할 문장 가져오기
    # text가 없으면 빈 문자열 사용
    text = request.get("text", "")


    # ------------------------------------------------------
    # 3-1. 글자 수 분석
    # mode가 length인 경우 문장의 글자 수를 계산
    # ------------------------------------------------------

    if mode == "length":

        # 문장의 전체 글자 수 계산
        length = len(text)

        # 분석 결과를 딕셔너리로 반환
        return {
            "result": length,
            "desc": f"전체 글자 수: {length}자"
        }


    # ------------------------------------------------------
    # 3-2. 감정 분석
    # 미리 정한 단어가 문장에 포함됐는지 검사
    # ------------------------------------------------------

    elif mode == "sentiment":

        # 긍정 단어가 하나라도 포함된 경우
        if any(
            word in text
            for word in ["좋아", "행복", "기쁨", "멋져"]
        ):
            sentiment = "positive"

        # 부정 단어가 하나라도 포함된 경우
        elif any(
            word in text
            for word in ["나빠", "싫어", "불만", "짜증"]
        ):
            sentiment = "negative"

        # 긍정·부정 단어가 모두 없는 경우
        else:
            sentiment = "neutral"

        # 감정 분석 결과 반환
        return {
            "result": sentiment,
            "desc": f"감정 분석 결과: {sentiment}"
        }


    # ------------------------------------------------------
    # 3-3. 키워드 탐지
    # 설비 이상과 관련된 키워드가 문장에 있는지 검사
    # ------------------------------------------------------

    elif mode == "keyword":

        # 탐지할 키워드 목록
        keywords = [
            "전류상승",
            "속도저하",
            "불량",
            "유량저하",
            "온도상승"
        ]

        # 문장에 포함된 키워드만 found에 저장
        found = [
            keyword
            for keyword in keywords
            if keyword in text
        ]

        # 발견한 키워드 결과 반환
        return {
            "result": found,
            "desc": (
                f"발견된 키워드: "
                f"{', '.join(found) if found else '없음'}"
            )
        }


    # ------------------------------------------------------
    # 3-4. 지원하지 않는 분석 모드
    # ------------------------------------------------------

    else:

        return {
            "error": f"지원하지 않는 모드입니다: {mode}"
        }


# ----------------------------------------------------------
# 4. 각각의 클라이언트를 담당하는 스레드 함수
#
# 클라이언트가 접속할 때마다 이 함수가 별도로 실행된다.
#
# client_socket : 접속한 클라이언트 전용 통신 소켓
# address       : 접속한 클라이언트의 IP와 포트
# ----------------------------------------------------------

def handle_client(client_socket, address):

    print(f"클라이언트 {address} 연결됨")


    # ------------------------------------------------------
    # 4-1. 해당 클라이언트의 요청을 계속 받는 반복문
    # ------------------------------------------------------

    while True:

        try:

            # ------------------------------------------------
            # 4-2. 클라이언트 요청 수신
            # 최대 2,048바이트까지 수신
            #
            # bytes → 문자열
            # ------------------------------------------------

            data = client_socket.recv(
                2048
            ).decode()


            # ------------------------------------------------
            # 4-3. 받은 데이터가 없으면 연결 종료로 판단
            # ------------------------------------------------

            if not data:

                print(f"{address} 연결 끊김")

                break


            # ------------------------------------------------
            # 4-4. JSON 문자열을 파이썬 딕셔너리로 변환
            # ------------------------------------------------

            try:

                request = json.loads(data)

                # 변환한 요청을 텍스트 분석 함수에 전달
                result = analyze_text(request)


            # ------------------------------------------------
            # 4-5. 올바른 JSON이 아닌 경우 오류 결과 생성
            # ------------------------------------------------

            except json.decoder.JSONDecodeError:

                result = {
                    "error": "잘못된 JSON 형태입니다."
                }


            # ------------------------------------------------
            # 4-6. 분석 결과를 JSON 문자열로 변환
            #
            # 파이썬 딕셔너리 → JSON 문자열
            # ------------------------------------------------

            response = json.dumps(
                result,
                ensure_ascii=False
            )


            # ------------------------------------------------
            # 4-7. JSON 결과를 바이트로 바꿔 클라이언트에 전송
            # ------------------------------------------------

            client_socket.sendall(
                response.encode()
            )


        # ----------------------------------------------------
        # 4-8. 클라이언트가 비정상적으로 종료된 경우
        # ----------------------------------------------------

        except ConnectionResetError:

            print(f"{address} 비정상 종료")

            break


    # ------------------------------------------------------
    # 4-9. 해당 클라이언트의 연결 종료
    # 서버 전체가 아니라 해당 클라이언트 소켓만 닫는다.
    # ------------------------------------------------------

    client_socket.close()

    print(f"클라이언트 {address} 세션 종료 완료")


# ----------------------------------------------------------
# 5. 서버를 실행하는 메인 함수
#
# 서버 소켓을 만들고 클라이언트 접속을 기다린다.
# 클라이언트가 접속할 때마다 새로운 스레드를 만든다.
# ----------------------------------------------------------

def start_server():


    # ------------------------------------------------------
    # 5-1. TCP 서버 소켓 생성
    #
    # AF_INET     : IPv4 주소 사용
    # SOCK_STREAM : TCP 통신 사용
    # ------------------------------------------------------

    server_socket = socket.socket(
        socket.AF_INET,
        socket.SOCK_STREAM
    )


    # ------------------------------------------------------
    # 5-2. 서버 소켓에 IP와 포트 바인딩
    # ------------------------------------------------------

    server_socket.bind(
        (HOST, PORT)
    )


    # ------------------------------------------------------
    # 5-3. 클라이언트 접속 대기 시작
    # 최대 20개의 접속 요청을 대기열에 저장
    # ------------------------------------------------------

    server_socket.listen(
        MAX_CLIENTS
    )

    print(f"AI 서버 실행 중: {HOST}:{PORT}")

    print(
        f"최대 {MAX_CLIENTS}개의 "
        f"클라이언트 동시 접속 가능\n"
    )


    try:

        # --------------------------------------------------
        # 5-4. 서버를 계속 실행하는 무한 반복문
        # --------------------------------------------------

        while True:


            # ------------------------------------------------
            # 5-5. 클라이언트가 접속할 때까지 대기
            #
            # client_socket : 해당 클라이언트 전용 소켓
            # addr          : 클라이언트 IP와 포트
            # ------------------------------------------------

            client_socket, addr = server_socket.accept()


            # ------------------------------------------------
            # 5-6. 접속한 클라이언트를 담당할 스레드 생성
            #
            # target : 스레드에서 실행할 함수
            # args   : 함수에 전달할 값
            # daemon : 서버 종료 시 스레드도 함께 종료
            # ------------------------------------------------

            client_thread = threading.Thread(
                target=handle_client,
                args=(client_socket, addr),
                daemon=True
            )


            # ------------------------------------------------
            # 5-7. 생성한 클라이언트 스레드 실행
            #
            # 실행 후 서버는 다시 accept()로 돌아가
            # 다음 클라이언트의 접속을 기다린다.
            # ------------------------------------------------

            client_thread.start()


    # ------------------------------------------------------
    # 5-8. Ctrl+C로 서버를 수동 종료한 경우
    # ------------------------------------------------------

    except KeyboardInterrupt:

        print("\n서버 수동 종료 감지")


    # ------------------------------------------------------
    # 5-9. 서버 소켓 종료
    # ------------------------------------------------------

    finally:

        server_socket.close()

        print("서버 완전 종료")


# ----------------------------------------------------------
# 6. 현재 파일을 직접 실행했을 때 서버 시작
# ----------------------------------------------------------

if __name__ == "__main__":

    start_server()


